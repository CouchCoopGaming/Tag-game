        public static Pose At(int clip, float u)
        {
            if (clip < 0) clip = 0;
            if (clip >= Count) clip = Count - 1;
            if (u < 0f) u = 0f;
            if (u > 1f) u = 1f;
            bool loop = Loops[clip];
            if (loop && u > 0.85f)
            {
                float fade = (u - 0.85f) / 0.15f;
                return Lerp(Sample(clip, u), Sample(clip, 0f), fade);
            }
            return Sample(clip, u);
        }

        public static Pose Lerp(Pose a, Pose b, float t)
        {
            Pose p;
            p.ThighL = a.ThighL + (b.ThighL - a.ThighL) * t;
            p.ThighR = a.ThighR + (b.ThighR - a.ThighR) * t;
            p.ThighYawL = a.ThighYawL + (b.ThighYawL - a.ThighYawL) * t;
            p.ThighYawR = a.ThighYawR + (b.ThighYawR - a.ThighYawR) * t;
            p.KneeL = a.KneeL + (b.KneeL - a.KneeL) * t;
            p.KneeR = a.KneeR + (b.KneeR - a.KneeR) * t;
            p.FootL = a.FootL + (b.FootL - a.FootL) * t;
            p.FootR = a.FootR + (b.FootR - a.FootR) * t;
            p.ArmPitchL = a.ArmPitchL + (b.ArmPitchL - a.ArmPitchL) * t;
            p.ArmPitchR = a.ArmPitchR + (b.ArmPitchR - a.ArmPitchR) * t;
            p.ArmYawL = a.ArmYawL + (b.ArmYawL - a.ArmYawL) * t;
            p.ArmYawR = a.ArmYawR + (b.ArmYawR - a.ArmYawR) * t;
            p.ElbowL = a.ElbowL + (b.ElbowL - a.ElbowL) * t;
            p.ElbowR = a.ElbowR + (b.ElbowR - a.ElbowR) * t;
            p.SpineYaw = a.SpineYaw + (b.SpineYaw - a.SpineYaw) * t;
            p.SpineRoll = a.SpineRoll + (b.SpineRoll - a.SpineRoll) * t;
            p.Head = a.Head + (b.Head - a.Head) * t;
            return p;
        }

        static Pose Sample(int clip, float u)
        {
            float t = u * (Keys - 1);
            int a = (int)t;
            if (a < 0) a = 0;
            if (a > Keys - 2) a = Keys - 2;
            int b = a + 1;
            float w = t - a;
            Pose p;
            p.ThighL = Mix(clip, a, b, 0, w);
            p.ThighR = Mix(clip, a, b, 1, w);
            p.ThighYawL = Mix(clip, a, b, 2, w);
            p.ThighYawR = Mix(clip, a, b, 3, w);
            p.KneeL = Mix(clip, a, b, 4, w);
            p.KneeR = Mix(clip, a, b, 5, w);
            p.FootL = Mix(clip, a, b, 6, w);
            p.FootR = Mix(clip, a, b, 7, w);
            p.ArmPitchL = Mix(clip, a, b, 8, w);
            p.ArmPitchR = Mix(clip, a, b, 9, w);
            p.ArmYawL = Mix(clip, a, b, 10, w);
            p.ArmYawR = Mix(clip, a, b, 11, w);
            p.ElbowL = Mix(clip, a, b, 12, w);
            p.ElbowR = Mix(clip, a, b, 13, w);
            p.SpineYaw = Mix(clip, a, b, 14, w);
            p.SpineRoll = Mix(clip, a, b, 15, w);
            p.Head = Mix(clip, a, b, 16, w);
            return p;
        }

        static float Mix(int clip, int a, int b, int channel, float w)
        {
            int ia = (clip * Keys + a) * Stride + channel;
            int ib = (clip * Keys + b) * Stride + channel;
            return Data[ia] + (Data[ib] - Data[ia]) * w;
        }
